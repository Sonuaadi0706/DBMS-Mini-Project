import fs from 'node:fs';
import path from 'node:path';
import { Client } from 'pg';
import { adminDatabaseUrl } from './lib/env';

/**
 * EXPLAIN ANALYZE before / after an index (spec 8.10, T-27). The demo database is tiny, so PostgreSQL would scan it
 * whatever indexes exist. To make the effect visible the script adds synthetic rows INSIDE A TRANSACTION, measures
 * the query with and without the index, and ROLLS BACK: the real data is never touched.
 */
async function plan(db: Client, sql: string, params: unknown[] = []): Promise<{ text: string; ms: number }> {
  const { rows } = await db.query(`EXPLAIN (ANALYZE, COSTS OFF, TIMING ON, SUMMARY ON) ${sql}`, params);
  const lines = rows.map((r) => r['QUERY PLAN'] as string);
  return { text: lines.join('\n'), ms: Number(lines.find((l) => l.startsWith('Execution Time'))!.match(/([\d.]+) ms/)![1]) };
}
const head = (t: string) => t.split('\n').slice(0, 14).join('\n');

async function main() {
  const db = new Client({ connectionString: adminDatabaseUrl() });
  await db.connect();
  let out = `# EXPLAIN ANALYZE evidence (T-27)\n\n_Generated by \`npm run docs:explain\`. Each experiment adds synthetic rows inside a transaction, times the query without and with the index, then rolls everything back._\n\n`;
  try {
    await db.query('SET search_path = projectpulse, public');
    const results: { name: string; index: string; before: number; after: number }[] = [];

    // ---- 1. Q2-style: overdue open tasks (partial index idx_tasks_due_open) ----------------------------
    await db.query('BEGIN');
    await db.query('ALTER TABLE tasks DISABLE TRIGGER USER');              // synthetic bulk rows: skip audit / evidence triggers
    await db.query(`INSERT INTO tasks(milestone_id, title, effort_hours, status, planned_completion_date, due_date, actual_completion_date, verified_by, verified_at)
      SELECT (SELECT MIN(milestone_id) FROM milestones), 'synthetic ' || g, 2,
             CASE WHEN g % 200 = 0 THEN 'todo' ELSE 'verified' END, CURRENT_DATE - (g % 400), CURRENT_DATE - (g % 400),
             CASE WHEN g % 200 = 0 THEN NULL ELSE CURRENT_DATE - (g % 400) END,
             CASE WHEN g % 200 = 0 THEN NULL ELSE (SELECT MIN(user_id) FROM users) END, CASE WHEN g % 200 = 0 THEN NULL ELSE now() END
        FROM generate_series(1, 60000) g`);
    await db.query('ANALYZE tasks');
    const q2 = `SELECT t.team_id, COUNT(*) AS overdue_tasks FROM tasks tk JOIN milestones m ON m.milestone_id = tk.milestone_id JOIN projects p ON p.project_id = m.project_id
                JOIN teams t ON t.team_id = p.team_id WHERE tk.due_date < CURRENT_DATE AND tk.status NOT IN ('done','verified') GROUP BY t.team_id HAVING COUNT(*) > 0`;
    await db.query('DROP INDEX idx_tasks_due_open');
    const b2 = await plan(db, q2);
    await db.query(`CREATE INDEX idx_tasks_due_open ON tasks(due_date) WHERE status NOT IN ('done','verified')`);
    await db.query('ANALYZE tasks');
    const a2 = await plan(db, q2);
    await db.query('ROLLBACK');
    results.push({ name: 'Q2 overdue open tasks (60,000 tasks, 0.5% open)', index: 'idx_tasks_due_open (partial index)', before: b2.ms, after: a2.ms });
    out += `## 1. Q2: teams with overdue open tasks\n\nIndex: \`idx_tasks_due_open ON tasks(due_date) WHERE status NOT IN ('done','verified')\`. Only open tasks can be overdue, so the partial index is tiny.\n\n**Before (index dropped): ${b2.ms} ms**\n\`\`\`\n${head(b2.text)}\n\`\`\`\n**After (index present): ${a2.ms} ms**\n\`\`\`\n${head(a2.text)}\n\`\`\`\n\n`;

    // ---- 2. Q11-style: open feedback per student (partial index idx_feedback_assignee_open) ------------
    await db.query('BEGIN');
    await db.query('ALTER TABLE feedback_items DISABLE TRIGGER USER');
    await db.query(`INSERT INTO feedback_items(review_id, created_by, assigned_user_id, description, resolution_status, resolved_at, verified_by, verified_at)
      SELECT (SELECT MIN(review_id) FROM reviews), (SELECT MIN(user_id) FROM users), (SELECT MIN(user_id) FROM users WHERE email LIKE 'student%') + (g % 14),
             'synthetic ' || g, CASE WHEN g % 250 = 0 THEN 'open' ELSE 'verified' END,
             CASE WHEN g % 250 = 0 THEN NULL ELSE now() END, CASE WHEN g % 250 = 0 THEN NULL ELSE (SELECT MIN(user_id) FROM users) END, CASE WHEN g % 250 = 0 THEN NULL ELSE now() END
        FROM generate_series(1, 60000) g`);
    await db.query('ANALYZE feedback_items');
    const q11 = `SELECT u.name, COUNT(*) AS open_items FROM feedback_items f JOIN users u ON u.user_id = f.assigned_user_id
                 WHERE f.resolution_status IN ('open','in_progress','reopened') GROUP BY u.user_id, u.name`;
    await db.query('DROP INDEX idx_feedback_assignee_open');
    await db.query('DROP INDEX idx_feedback_status');
    const b11 = await plan(db, q11);
    await db.query(`CREATE INDEX idx_feedback_assignee_open ON feedback_items(assigned_user_id) WHERE resolution_status IN ('open','in_progress','reopened')`);
    await db.query('ANALYZE feedback_items');
    const a11 = await plan(db, q11);
    await db.query('ROLLBACK');
    results.push({ name: 'Q11 open feedback per student (60,000 items, 0.4% open)', index: 'idx_feedback_assignee_open (partial index)', before: b11.ms, after: a11.ms });
    out += `## 2. Q11: students with open feedback\n\nIndex: \`idx_feedback_assignee_open ON feedback_items(assigned_user_id) WHERE resolution_status IN ('open','in_progress','reopened')\`.\n\n**Before (indexes dropped): ${b11.ms} ms**\n\`\`\`\n${head(b11.text)}\n\`\`\`\n**After: ${a11.ms} ms**\n\`\`\`\n${head(a11.text)}\n\`\`\`\n\n`;

    // ---- 3. Q6-style: nearest neighbours (HNSW) ---------------------------------------------------------
    await db.query('BEGIN');
    await db.query('ALTER TABLE project_embeddings DISABLE TRIGGER USER');
    await db.query(`INSERT INTO project_embeddings(project_id, course_id, section_type, chunk_index, chunk_text, embedding, model_name)
      SELECT p.project_id, p.course_id, 'document_chunk', g, 'synthetic', (SELECT array_agg(random()::real) FROM generate_series(1, 384) WHERE g > 0 AND p.project_id > 0)::vector, 'synthetic-random'
        FROM generate_series(1, 1500) g CROSS JOIN (SELECT project_id, course_id FROM projects ORDER BY project_id LIMIT 4) p`);
    await db.query('ANALYZE project_embeddings');
    const probe = (await db.query(`SELECT embedding::text AS v FROM project_embeddings WHERE model_name = 'synthetic-random' LIMIT 1`)).rows[0].v;
    const q6 = `SELECT project_id FROM project_embeddings ORDER BY embedding <=> $1::vector LIMIT 5`;
    await db.query('DROP INDEX idx_embeddings_hnsw');
    const b6 = await plan(db, q6, [probe]);
    await db.query(`CREATE INDEX idx_embeddings_hnsw ON project_embeddings USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64)`);
    await db.query('ANALYZE project_embeddings');
    await db.query('SET LOCAL hnsw.ef_search = 100');
    const a6 = await plan(db, q6, [probe]);
    await db.query('ROLLBACK');
    results.push({ name: 'Q6 five nearest vectors (6,000 vectors, 384 dims)', index: 'idx_embeddings_hnsw (HNSW, cosine)', before: b6.ms, after: a6.ms });
    out += `## 3. Q6: nearest-neighbour search\n\nIndex: \`idx_embeddings_hnsw USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64)\`. Without it PostgreSQL measures the distance to every vector; HNSW walks a small graph instead (approximate, hence \`ef_search = 100\` for good recall).\n\n**Before (index dropped): ${b6.ms} ms**\n\`\`\`\n${head(b6.text)}\n\`\`\`\n**After: ${a6.ms} ms**\n\`\`\`\n${head(a6.text)}\n\`\`\`\n\n`;

    const rows = results.map((r) => `| ${r.name} | ${r.index} | ${r.before} ms | ${r.after} ms | ${(r.before / r.after).toFixed(1)}x |`).join('\n');
    out = out.replace('## 1.', `## Summary\n\n| Query | Index | Before | After | Speed-up |\n|---|---|---|---|---|\n${rows}\n\nQ4 (milestones with unresolved feedback) uses \`<>\`, which no B-tree index can answer, so it is not index-driven; its joins use the primary-key and \`idx_reviews_milestone\` indexes. On the real demo data (a few dozen rows per table) PostgreSQL chooses sequential scans whatever indexes exist, which is why the synthetic rows are needed to show the effect.\n\n## 1.`);
    fs.writeFileSync(path.resolve(__dirname, '../docs/EXPLAIN_ANALYZE.md'), out);
    console.log(results.map((r) => `${r.name}: ${r.before} ms -> ${r.after} ms`).join('\n'));
  } catch (e) {
    await db.query('ROLLBACK').catch(() => undefined);
    throw e;
  } finally {
    await db.end();
  }
}

main().catch((e) => { console.error(e.message ?? e); process.exit(1); });
