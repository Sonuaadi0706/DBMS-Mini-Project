import fs from 'node:fs';
import path from 'node:path';

/**
 * Turns a vitest JSON result (`vitest run --reporter=json --outputFile=...`) into docs/TEST_RESULTS.md: the spec's
 * T-01 ... T-30 table with the REAL outcome of the automated tests that carry each id in their name.
 *   npm run test:report      (runs the whole suite, including the data-changing tests, then restores the demo)
 */
const CASES: [string, string, string][] = [
  ['T-01', 'API', 'Login as each of the four roles; role-specific dashboard shown'],
  ['T-02', 'API', 'Wrong password 5 times: account locked 15 minutes, generic message'],
  ['T-03', 'DB', 'users.password_hash holds bcrypt hashes only; no plain text'],
  ['T-04', 'API', 'Student calls guide-only endpoints: 403 and nothing changes'],
  ['T-05', 'API', "Student of team A requests team B's documents, feedback, evidence: no data leaked"],
  ['T-06', 'DB/API', 'Invalid dates, negative effort or weightage are rejected (CHECK constraints)'],
  ['T-07', 'DB/API', 'Duplicate active project, student in two teams, duplicate title: unique violations'],
  ['T-08', 'DB', 'Milestone weightage total above 100 rejected by the constraint trigger'],
  ['T-09', 'DB', 'Illegal status change (planned to approved, todo to verified) rejected'],
  ['T-10', 'DB', 'UPDATE / DELETE on proposal_actions and audit_logs: append-only'],
  ['T-11', 'DB', 'Guide allocated to own team, or non-guide allocated as guide: rejected'],
  ['T-12', 'DB', 'Overdue milestone creates one risk event, no duplicates on repeat'],
  ['T-13', 'DB', 'sp_recalculate_risk matches the hand calculation; breakdown present'],
  ['T-14', 'DB', 'risk_assessments with a level that does not match the score: CHECK violation'],
  ['T-15', 'API+DB', 'Failed milestone submission rolls back completely (deliverable, version, review, audit, file, Mongo)'],
  ['T-16', 'API+DB', 'Valid submission: deliverable, version, status, review requests, audit row, Mongo confirmed'],
  ['T-17', 'DB', 'Versions inserted without a number are numbered 1, 2, 3'],
  ['T-18', 'API+DB', 'Approve / reject / request revision: status, immutable history row, audit row; reject needs a comment'],
  ['T-19', 'DB', 'Status changes write a STATUS_CHANGE audit row with the user id'],
  ['T-20', 'API+DB', 'A draft deliverable can be deleted (audited); a submitted one cannot'],
  ['T-21', 'DB', 'Deleting a project with milestones, or a user referenced by tasks, is blocked (RESTRICT)'],
  ['T-22', 'API+vector', 'Similarity search for Echo returns Alpha above threshold; other course never returned'],
  ['T-23', 'API+UI', 'Faculty decision saved with reviewer, time and audit; student hint is generic'],
  ['T-24', 'DB', 'Verifying a task creates verified evidence; unverified evidence is excluded from the summary'],
  ['T-25', 'DB', 'Approving a milestone with a missing mandatory deliverable type is blocked'],
  ['T-26', 'Mongo', 'Aggregations A1-A4 match the seeded data'],
  ['T-27', 'DB', 'EXPLAIN ANALYZE before/after indexes; HNSW and partial indexes used'],
  ['T-28', 'DB', 'Full-text search for "event" returns Alpha, Echo, Foxtrot ranked'],
  ['T-29', 'Repo', 'No secrets committed; .env ignored'],
  ['T-30', 'UI', "Each role's dashboard renders all required widgets with the seed data"],
];

interface Assertion { fullName: string; status: string; title: string }
interface FileResult { name: string; assertionResults: Assertion[] }

function main() {
  const input = process.argv[2];
  if (!input) throw new Error('usage: tsx scripts/test-report.ts <vitest-json> [out.md]');
  const data = JSON.parse(fs.readFileSync(input, 'utf8')) as { numTotalTests: number; numPassedTests: number; numFailedTests: number; numPendingTests: number; testResults: FileResult[] };
  const all = data.testResults.flatMap((f) => f.assertionResults.map((a) => ({ ...a, file: path.relative(process.cwd(), f.name) })));
  let md = `# Test results\n\n_Generated by \`npm run test:report\` from a full run of the automated suite, including the tests that change data (the demo is restored afterwards)._\n\n`;
  md += `**${data.numPassedTests} of ${data.numTotalTests} tests passed** (${data.numFailedTests} failed, ${data.numPendingTests} skipped).\n\n`;
  md += `## Spec test cases T-01 to T-30\n\n| ID | Level | Test case | Result | Automated evidence |\n|---|---|---|---|---|\n`;
  for (const [id, level, text] of CASES) {
    const hits = all.filter((a) => new RegExp(`\\b${id}\\b|\\b${id.replace('T-', 'T-')}/`).test(a.fullName) || new RegExp(`T-\\d\\d/${id.slice(2)}\\b|T-\\d\\d / ${id.slice(2)}\\b`).test(a.fullName));
    const passed = hits.filter((h) => h.status === 'passed').length;
    const failed = hits.filter((h) => h.status === 'failed').length;
    const result = hits.length === 0 ? 'not automated' : failed ? `FAIL (${failed})` : passed === hits.length ? 'PASS' : 'skipped';
    const files = [...new Set(hits.map((h) => h.file))].join(', ');
    md += `| ${id} | ${level} | ${text} | ${result}${hits.length ? ` (${passed}/${hits.length})` : ''} | ${files || ''} |\n`;
  }
  md += `\n## All test files\n\n| File | Tests | Passed |\n|---|---|---|\n`;
  for (const f of data.testResults) {
    const a = f.assertionResults;
    md += `| ${path.relative(process.cwd(), f.name)} | ${a.length} | ${a.filter((x) => x.status === 'passed').length} |\n`;
  }
  const out = process.argv[3] ?? path.resolve(__dirname, '../docs/TEST_RESULTS.md');
  fs.writeFileSync(out, md);
  console.log(`Wrote ${path.relative(process.cwd(), out)}: ${data.numPassedTests}/${data.numTotalTests} passed`);
  const missing = CASES.filter(([id]) => !md.includes(`| ${id} |`) || md.match(new RegExp(`\\| ${id} \\|[^\\n]*not automated`)));
  if (missing.length) console.log('Not automated:', missing.map((m) => m[0]).join(', '));
}

main();
